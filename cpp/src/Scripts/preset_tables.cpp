// 段 0 的 span（主段内偏移即段 0 偏移）。
std::span<uint8_t> mainData(const SegmentTable &seg_table) {
    return seg_table.data(SegmentedAddress { 0x00, 0 });
}

// 在段 0 里按模型列指纹找 sMacroObjectPresets；返回段 0 内偏移或 -1。
int32_t locateMacroTable(const std::span<uint8_t> &seg0) {
    for (size_t i = 0; i + 8 * 24 <= seg0.size(); i += 8) {
        size_t run = 0;
        for (; run < 24; run++) {
            if (readInt<uint16_t>(seg0, i + run * 8 + 4) != kMacroModelAnchor[run]) {
                break;
            }
        }
        if (run >= 20) {
            return static_cast<int32_t>(i);
        }
    }
    return -1;
}

// 在段 0 里按模型列指纹找 sSpecialObjectPresets；返回段 0 内偏移或 -1。
int32_t locateSpecialTable(const std::span<uint8_t> &seg0) {
    for (size_t i = 0; i + 8 * 16 <= seg0.size(); i += 8) {
        size_t run = 0;
        for (; run < 16; run++) {
            if (seg0[i + run * 8 + 3] != kSpecialModelAnchor[run]) {
                break;
            }
        }
        if (run >= 10) {
            return static_cast<int32_t>(i);
        }
    }
    return -1;
}

